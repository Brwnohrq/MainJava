public class Cliente {

    private int id;
    private String name;
    private String cpf;


    public Cliente(String name, String cpf) {
        this.name = name;
        this.cpf = cpf;
    }

    public int getId() {
        return id;
    }

    public String getName() {
        return name;
    }

    public String getCpf() {
        return cpf;
    }


}







